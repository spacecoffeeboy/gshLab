import {test} from 'node:test';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {createElement} from 'react';
import {KoreaTest} from '../components/korea-test';
import {sampleQuestion} from '../lib/korea-test';
const dom=new JSDOM('<!doctype html><html><body></body></html>',{url:'http://localhost'});
Object.assign(globalThis,{window:dom.window,self:dom.window,document:dom.window.document,HTMLElement:dom.window.HTMLElement});
dom.window.scrollTo=()=>{};
test('sample journey requires a pick, allows changes, then explains the pairing without fabricated rankings or levels',async()=>{
 const {render,fireEvent,cleanup}=await import('@testing-library/react');
 const view=render(createElement(KoreaTest));
 const reveal=view.getByRole('button',{name:/See the answer/});
 assert.equal((reveal as HTMLButtonElement).disabled,true);
 assert.equal(view.queryByText(sampleQuestion.explanation),null);
 fireEvent.click(view.getByRole('button',{name:/A Kimchi/}));
 fireEvent.click(view.getByRole('button',{name:/B Pickled radish/}));
 fireEvent.click(reveal);
 assert.ok(view.getByText(sampleQuestion.explanation));
 assert.ok(view.getByText(sampleQuestion.takeaway));
 assert.ok(view.getByText('ANOTHER GOOD PAIRING'));
 assert.equal(view.queryByRole('img',{name:'Correct'}),null);
 assert.ok(view.getByText(/not a measured popularity ranking/));
 assert.equal(view.queryByText('Honorary Korean'),null);
 assert.equal(view.getByRole('link',{name:/Back to home/}).getAttribute('href'),'/');
 fireEvent.click(view.getByRole('button',{name:'Try this question again'}));
 assert.equal((view.getByRole('button',{name:/See the answer/}) as HTMLButtonElement).disabled,true);
 assert.equal(view.queryByText(sampleQuestion.explanation),null);
 fireEvent.click(view.getByRole('button',{name:/A Kimchi/}));
 fireEvent.click(view.getByRole('button',{name:/See the answer/}));
 assert.ok(view.getByText('A CLASSIC PICK'));
 assert.ok(view.getByRole('img',{name:'Correct'}));
 cleanup();
});
