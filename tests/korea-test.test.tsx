import {test} from 'node:test';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {createElement} from 'react';
import {KoreaTest} from '../components/korea-test';
import {sampleQuestion} from '../lib/korea-test';
const dom=new JSDOM('<!doctype html><html><body></body></html>',{url:'http://localhost'});
Object.assign(globalThis,{window:dom.window,self:dom.window,document:dom.window.document,HTMLElement:dom.window.HTMLElement});
dom.window.scrollTo=()=>{};
test('selection checks immediately; explanation expands under the unchanged question and retry resets both',async()=>{
 const {render,fireEvent,cleanup}=await import('@testing-library/react');
 const view=render(createElement(KoreaTest));
 const reveal=view.getByRole('button',{name:/View explanation/});
 const explanation=view.container.querySelector('#sample-explanation') as HTMLElement;
 assert.equal((reveal as HTMLButtonElement).disabled,true);
 assert.equal(explanation.hidden,true);
 fireEvent.click(view.getByRole('button',{name:/B Pickled radish/}));
 assert.ok(view.getByRole('img',{name:'Correct'}));
 assert.ok(view.container.querySelector('.success-tick.is-static'));
 assert.ok(view.getByText(/The classic sidekick is kimchi/));
 assert.equal(explanation.hidden,true);
 assert.equal(view.getByRole('button',{name:/A Kimchi/}).matches(':disabled'),true);
 fireEvent.click(reveal);
 assert.equal(explanation.hidden,false);
 assert.equal(reveal.getAttribute('aria-expanded'),'true');
 assert.ok(view.getByRole('heading',{name:sampleQuestion.question}));
 assert.ok(view.getByText(sampleQuestion.explanation));
 fireEvent.click(view.getByRole('button',{name:/Hide explanation/}));
 assert.equal(explanation.hidden,true);
 fireEvent.click(view.getByRole('button',{name:/View explanation/}));
 fireEvent.click(view.getByRole('button',{name:'Try this question again'}));
 assert.equal(explanation.hidden,true);
 assert.equal(view.queryByRole('img',{name:'Correct'}),null);
 fireEvent.click(view.getByRole('button',{name:/A Kimchi/}));
 assert.ok(view.getByRole('img',{name:'Correct'}));
 assert.equal(view.container.querySelector('.success-tick.is-static'),null);
 assert.equal(explanation.hidden,true);
 cleanup();
});
